#!/usr/bin/env node
// build.mjs — the skill pages' stylesheet from the Ultrademo design system. tokens.json here is a copy of the style guide's; this writes ui.css with
// the fonts, the Flow tokens (light, and dark under prefers-color-scheme or data-theme="dark") and the shared components
// (eyebrow, buttons, cards, chips, focus). Pages link /ui/ui.css; each skill server serves plan/ui/ at /ui/.
//   node plan/ui/build.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const T = JSON.parse(fs.readFileSync(path.join(HERE, 'tokens.json'), 'utf8'));
const palette = Object.fromEntries(T.color.tokens.filter((t) => typeof t.value === 'string').map((t) => [t.name, t.value]));
const resolve = (v) => String(v).replace(/^\{(.+)\}$/, (_, n) => palette[n] ?? v);
const vars = (theme) => T.color.tokens.map((t) => `--${t.name}:${resolve(typeof t.value === 'string' ? t.value : t.value[theme])}`).join(';')
  + ';' + (T.shadow.tokens || []).map((t) => `--${t.name}:${typeof t.value === 'string' ? t.value : t.value[theme]}`).join(';');
const fixed = [
  ...T.spacing.tokens.map((t) => `--${t.name}:${t.value}`),
  ...T.radius.tokens.map((t) => `--${t.name}:${t.value}`),
  ...Object.entries(T.type.families).map(([k, v]) => `--font-${k}:${v}`),
].join(';');
const faces = T.type.fonts.map((f) => `@font-face{font-family:"${f.family}";src:url("/ui/fonts/${path.basename(f.file)}") format("truetype");font-weight:${f.weight};font-style:${f.style};font-display:swap}`)
  .filter((r) => fs.existsSync(path.join(HERE, 'fonts', r.match(/fonts\/([^"]+)"/)[1])));

const css = `/* Generated by plan/ui/build.mjs from tokens.json (the Ultrademo design system, Flow variant). Do not edit by hand. */
${faces.join('\n')}
:root{${fixed};${vars('flow')};--ud-display:var(--font-flow-display);--ud-body:var(--font-flow-body);--ud-ease:cubic-bezier(.76,0,.24,1);--ud-action-edge:var(--ink);color-scheme:light}
@media (prefers-color-scheme:dark){:root:not([data-theme="light"]){${vars('flow-dark')};--ud-action-edge:transparent;color-scheme:dark}}
:root[data-theme="dark"]{${vars('flow-dark')};--ud-action-edge:transparent;color-scheme:dark}
/* the lime primary button carries an ink outline on light grounds (the guide's Button component) */
button.primary,.ud-btn--primary{box-shadow:inset 0 0 0 1.5px var(--ud-action-edge)}
/* Shared pieces, from the guide's components (bundle.css) */
.ud-logo{display:block;height:28px;width:auto}.ud-logo--dark{display:none}
.ud-head{display:flex;align-items:center;justify-content:space-between;gap:12px}
.ud-theme{display:inline-grid;place-items:center;width:36px;height:36px;padding:0;border-radius:50%;border:1px solid var(--line);background:var(--surface);color:var(--text);cursor:pointer}
.ud-theme:hover{border-color:var(--text)}
/* the logo and the stage bar (D-79) stay at the top while the page scrolls */
.ud-pin{position:sticky;top:0;z-index:20;background:var(--surface-soft);padding:12px 0 10px;margin-bottom:16px;border-bottom:1px solid transparent}
.ud-pin.stuck{border-bottom-color:var(--line);box-shadow:0 4px 14px rgba(0,0,0,.05)}.ud-pin .ud-head{margin:0 0 8px}
.ud-progress{list-style:none;display:flex;gap:6px;flex-wrap:wrap;margin:0;padding:0;font-size:13px}
.ud-progress li{display:flex;align-items:center;gap:6px;padding:5px 12px 5px 6px;border:1px solid var(--line);border-radius:999px;color:var(--text-muted);background:var(--surface)}
.ud-progress li span{display:inline-grid;place-items:center;width:20px;height:20px;border-radius:50%;background:var(--surface-soft);font-size:11.5px;font-weight:700}
.ud-progress li.now{color:var(--text);border-color:var(--text);font-weight:600}.ud-progress li.now span{background:var(--text);color:var(--surface)}
.ud-progress li.done{color:var(--text)}.ud-progress li.done span{background:var(--surface-highlight)}
@media (prefers-color-scheme:dark){:root:not([data-theme="light"]) .ud-logo--light{display:none}:root:not([data-theme="light"]) .ud-logo--dark{display:block}}
:root[data-theme="dark"] .ud-logo--light{display:none}:root[data-theme="dark"] .ud-logo--dark{display:block}
.ud-eyebrow{display:inline-flex;gap:10px;align-items:center;font:500 12px/1.3 var(--font-mono);letter-spacing:.12em;text-transform:uppercase;color:var(--text-muted)}
.ud-eyebrow::before{content:"";width:8px;height:8px;border-radius:50%;background:var(--accent)}
.ud-h{margin:0;font-family:var(--ud-display);font-weight:800;letter-spacing:-.035em;line-height:1.04;color:var(--text);text-wrap:balance}
:where(a,button,input,textarea,select,summary,[tabindex]):focus-visible{outline:3px solid var(--focus);outline-offset:3px}
@media (prefers-reduced-motion:reduce){*,*::before,*::after{transition:none!important;animation:none!important}}
`;
fs.writeFileSync(path.join(HERE, 'ui.css'), css);
console.log(`${path.join(HERE, 'ui.css')}: ${faces.length} fonts, ${T.color.tokens.length} colour tokens`);
